ALTER TABLE BOOKS
    ADD COLUMN BESTSELLER BOOLEAN DEFAULT 0;

SET SQL_SAFE_UPDATES = 0;

UPDATE BOOKS B
    JOIN (
    SELECT BOOK_ID
    FROM RENTS
    GROUP BY BOOK_ID
    HAVING COUNT(*) > 2
    ) R ON b.BOOK_ID = R.BOOK_ID
    SET B.BESTSELLER = TRUE;

SET SQL_SAFE_UPDATES = 1;

